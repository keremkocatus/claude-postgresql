async def test_partition_clone_foreign_keys_are_hidden(make_backend: MakeBackend) -> None:
    backend = await make_backend()
    child = await introspection.describe_table(backend, "ix", "pchild")
    foreign_keys = [row for row in _data_rows(child.text, "Constraints") if "| FOREIGN KEY |" in row]
    assert len(foreign_keys) == 1, child.text
    assert "REFERENCES ix.pref(id)" in foreign_keys[0]

    partition = await introspection.describe_table(backend, "ix", "pchild_1")
    foreign_keys = [row for row in _data_rows(partition.text, "Constraints") if "| FOREIGN KEY |" in row]
    assert len(foreign_keys) == 1, partition.text

    referenced = await introspection.describe_table(backend, "ix", "pref")
    referenced_by = _data_rows(referenced.text, "Referenced by")
    assert len(referenced_by) == 1, referenced.text
    assert referenced_by[0].startswith("| ix.pchild | ")


