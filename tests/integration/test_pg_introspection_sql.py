async def test_query_truncated_by_row_limit_and_by_size(make_backend: MakeBackend) -> None:
    by_rows = await make_backend(max_rows=2)
    output = await run_query(by_rows, "SELECT i FROM generate_series(1, 5) AS i", [])
    assert output.text.startswith("Showing the first 2 rows; the query returned more (row limit 2).")

    by_size = await make_backend(max_rows=500, max_response_bytes=1024)
    output = await run_query(by_size, "SELECT repeat('x', 300) FROM generate_series(1, 50)", [])
    assert "response size limit (~1024 bytes)" in output.text
    assert output.rows is not None and output.rows < 50


async def test_execute_reports_the_true_count_of_a_cut_returning(make_backend: MakeBackend) -> None:
    backend = await make_backend(max_rows=2)
    output = await run_execute(backend, [("UPDATE ix.t SET note = note RETURNING id", [])])
    assert "1. UPDATE 5" in output.text
    assert "showing the first 2 returned rows; more were returned" in output.text
    assert output.rows == 5


async def test_write_level_explain_analyze_rolls_back(make_backend: MakeBackend) -> None:
    backend = await make_backend()
    sql = "INSERT INTO ix.t (note) VALUES ('explained')"
    output = await run_explain(backend, Access.WRITE, sql, [], analyze=True, buffers=False)
    assert "sequence increments and other non-transactional effects persist" in output.text
    assert "\n```\n" in output.text and output.text.endswith("\n```")
    count = await run_query(backend, "SELECT count(*) FROM ix.t", [])
    assert "| 5 |" in count.text
