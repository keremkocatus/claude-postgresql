MakeBackend = Callable[..., Awaitable[PostgresBackend]]


@pytest.fixture
async def make_backend(pg_dsn: str) -> AsyncIterator[MakeBackend]:
    admin = await asyncpg.connect(pg_dsn)
    try:
        await admin.execute(SETUP_SQL)
    finally:
        await admin.close()
    opened: list[PostgresBackend] = []

    async def make(*, allowed_schemas: list[str] | None = None, **limits: Any) -> PostgresBackend:
        values: dict[str, Any] = {
            "dsn": pg_dsn,
            "mode": "write",
            "tls": {"mode": "disable"},
            "statement_timeout": "20s",
            "pool": {"min_size": 1, "max_size": 2, "write_max_size": 1},
            "limits": limits,
            "allowed_schemas": allowed_schemas or [],
        }
        config = make_config(connections={"main": values})
        backend = PostgresBackend("main", config.connections["main"])
        await backend.open()
        opened.append(backend)
        return backend

    yield make
    for backend in opened:
        await backend.close()


def _data_rows(text: str, title: str) -> list[str]:
    """Data rows of the Markdown table under ``### <title>`` (header and separator rows dropped)."""
    section = text.split(f"### {title}", 1)[1].split("\n### ", 1)[0]
    table = [line for line in section.splitlines() if line.startswith("| ")]
    return [line for line in table[1:] if not line.startswith("| --- ")]


# -- search_path hijack (CVE-2018-1058 pattern) ----------------------------------------------------------------


async def test_shadowing_catalog_functions_in_public_has_no_effect(pg_dsn: str, make_backend: MakeBackend) -> None:
    admin = await asyncpg.connect(pg_dsn)
    await admin.execute(
        """
        DO $$ BEGIN
            IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'ix_attacker') THEN
                CREATE ROLE ix_attacker LOGIN PASSWORD 'ix_attacker_pw';
            END IF;
        END $$;
        GRANT CREATE ON SCHEMA public TO ix_attacker;
        """
    )
    attacker = await asyncpg.connect(pg_dsn, user="ix_attacker", password="ix_attacker_pw")
    try:
        await attacker.execute(
            "CREATE FUNCTION public.obj_description(oid, text) RETURNS text "
            "LANGUAGE sql AS $$ SELECT 'HIJACKED-MARKER' $$"
        )
        # Precondition: with the default search_path the shadow really wins for an untyped literal.
        hijacked = await admin.fetchval("SELECT obj_description('public'::regnamespace, 'pg_namespace')")
        assert hijacked == "HIJACKED-MARKER"

        backend = await make_backend()
        schemas = await introspection.list_schemas(backend)
        tables = await introspection.list_tables(backend, "public", name_like="ix_%")
        assert "HIJACKED-MARKER" not in schemas.text
        assert "HIJACKED-MARKER" not in tables.text
        assert "| ix | " in schemas.text and "introspection fixtures" in schemas.text
        assert "parent table" in tables.text
    finally:
        await attacker.execute("DROP FUNCTION IF EXISTS public.obj_description(oid, text)")
        await attacker.close()
        await admin.execute("REVOKE CREATE ON SCHEMA public FROM ix_attacker")
        await admin.close()


